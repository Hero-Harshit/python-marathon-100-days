# Set Operations
# Create two sets and demonstrate their union, intersection, difference, and symmetric difference.

set1 = {1, 2, 3, 4, 5}
set2 = {4, 5, 6, 7, 8}

print(f"Set 1: {set1}")
print(f"Set 2: {set2}")

print(f"Union (set1 | set2): {set1 | set2}")
print(f"Intersection (set1 & set2): {set1 & set2}")
print(f"Difference (set1 - set2): {set1 - set2}")
print(f"Symmetric Difference (set1 ^ set2): {set1 ^ set2}")
