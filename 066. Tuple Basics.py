# Tuple Basics
# Create a tuple containing five values and print individual elements using indexing.

my_tuple = (10, 20, "hello", 3.14, True)
print(f"The tuple is: {my_tuple}")

print(f"Element at index 0: {my_tuple[0]}")
print(f"Element at index 2: {my_tuple[2]}")
print(f"Element at index -1: {my_tuple[-1]}")
